  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  MX_USART3_UART_Init();
  MX_UART4_Init();
  MX_UART5_Init();

  printf("%s\r\n", version_str);

  if (flags & RCC_CSR_IWDGRSTF) {
    printf("IWDG reset\r\n");
  }
  if (flags & RCC_CSR_PORRSTF) {
    printf("Power-on reset\r\n");
    Relay_0_On();
    Relay_1_On();
    printf("Arms power on start\r\n");
    HAL_Delay(10000);
    Relay_0_Off();
    Relay_1_Off();
    printf("Arms power on end\r\n");
  }
  if (flags & RCC_CSR_SFTRSTF) {
    printf("Software reset\r\n");
  }
  if (flags & RCC_CSR_LPWRRSTF) {
    printf("Low-power reset\r\n");
  }

