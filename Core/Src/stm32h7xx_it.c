/**
  * @brief This function handles USART1 global interrupt.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */
		if (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE))
  {
      __HAL_UART_CLEAR_IDLEFLAG(&huart1);               // ��� IDLE ��־
      HAL_UART_DMAStop(&huart1);                        // ֹͣ DMA

      uart1_data_lenth = UART1_BUFFER_SIZE - __HAL_DMA_GET_COUNTER(huart1.hdmarx);  // ��ȡ��Ч����
			//set_uartReceiveFlag(1);
      if (uart1_data_lenth > 0 && uart1_data_lenth < UART1_BUFFER_SIZE)
      {
          memcpy(uart1_buffer_data, uart1_buffer, uart1_data_lenth);
          uart1_buffer_data[uart1_data_lenth] = '\0';
          set_uartReceiveFlag(1);
				memset(uart1_buffer,0,UART1_BUFFER_SIZE);
      }
			
      HAL_UART_Receive_DMA(&huart1, uart1_buffer, UART1_BUFFER_SIZE);  // �������� DMA ����
  }

  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */
	
	
  /* USER CODE END USART1_IRQn 1 */
}

